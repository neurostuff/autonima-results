#!/usr/bin/env python3
"""Document what actually differs between a project's runs at each comparison tier.

WHY THIS EXISTS

run_categories.yaml names a run per (project, family, tier), and run_tiers.py defines what the
tiers mean, but neither says what CHANGED between them. For the overfitting argument that
distinction is the whole point: a reader needs to see that, say, problem_solving v1 -> v2 moved
the annotation block and nothing else, or that cue_reactivity v4 -> v5 relaxed scope in the
direction that recovers false negatives.

This walks each project's tier ladder and diffs the configs block by block, so the table is
derived from the configs themselves rather than from their headers. Headers have been wrong
before -- see the 2026-11-03 commit withdrawing two "benchmark-tuned" labels.

    scripts/compile_tier_specs.py [--output reports/tier_specifications.md]
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
from run_tiers import TIERS, load_registry  # noqa: E402

REPO_ROOT = Path(__file__).resolve().parent.parent
PROJECTS = REPO_ROOT / "projects"
LADDER = ("initial", "untuned", "benchmark_tuned", "best")


def availability(project: str, run: str) -> str:
    """Whether a registered run actually has outputs on disk.

    A registered name is not a usable run. cue_reactivity's untuned annotation-only arm, for
    instance, has a config but no outputs until it is executed -- and a comparison that silently
    skipped it would quietly shrink the map-level n instead of failing.
    """
    d = PROJECTS / project / run
    if not (d / "outputs" / "nimads_studyset.json").exists():
        return "no outputs"
    if not (d / "outputs" / "meta_analysis_results").is_dir():
        return "studyset only"
    return "ok"


def cfg(project: str, run: str) -> dict | None:
    p = PROJECTS / project / f"{run}.yaml"
    if not p.exists():
        p = PROJECTS / project / f"{run}.yml"
    return yaml.safe_load(p.read_text()) if p.exists() else None


def header(project: str, run: str, limit: int = 2) -> str:
    """The config's own first words about itself, for the provenance column."""
    p = PROJECTS / project / f"{run}.yaml"
    if not p.exists():
        return ""
    out: list[str] = []
    for line in p.read_text().splitlines():
        if line.startswith("#"):
            t = line.lstrip("#").strip()
            if t:
                out.append(t)
        elif out or line.strip():
            break
        if len(out) >= limit:
            break
    return " ".join(out)


def crit(block: dict | None) -> tuple[tuple, tuple]:
    b = block or {}
    return (tuple(b.get("inclusion_criteria") or ()),
            tuple(b.get("exclusion_criteria") or ()))


def delta(before: dict | None, after: dict | None) -> str:
    """Describe a criteria block's change as counts, not prose."""
    bi, be = crit(before)
    ai, ae = crit(after)
    if (bi, be) == (ai, ae):
        return "unchanged"
    bits = []
    for name, x, y in (("incl", bi, ai), ("excl", be, ae)):
        if x == y:
            continue
        added = [i for i in y if i not in x]
        removed = [i for i in x if i not in y]
        reworded = len(x) == len(y) and len(added) == len(removed) == len(x)
        if reworded:
            bits.append(f"{name} {len(x)} reworded in place")
        else:
            bits.append(f"{name} {len(x)}->{len(y)} (+{len(added)}/-{len(removed)})")
    return "; ".join(bits) or "unchanged"


def search_delta(before: dict | None, after: dict | None) -> str:
    b, a = (before or {}).get("search") or {}, (after or {}).get("search") or {}
    if b == a:
        return "unchanged"
    bits = []
    if (b.get("query") or "") != (a.get("query") or ""):
        bits.append("query rewritten")
    for k in ("date_from", "date_to"):
        if b.get(k) != a.get(k):
            bits.append(f"{k} {b.get(k)}->{a.get(k)}")
    if b.get("pmids_file") != a.get("pmids_file"):
        bits.append("pmids_file changed")
    return "; ".join(bits) or "other search fields"


def columns(c: dict | None) -> list[str]:
    anns = ((c or {}).get("annotation") or {}).get("annotations") or []
    return [a.get("name") for a in anns if isinstance(a, dict)]


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--output", default=str(REPO_ROOT / "reports" / "tier_specifications.md"))
    args = ap.parse_args(argv)

    reg = load_registry()
    L: list[str] = []
    w = L.append

    w("# Run tiers and what differs between them\n")
    w("Generated by `scripts/compile_tier_specs.py`. Every difference below is computed from the "
      "configs themselves, not from their headers.\n")

    w("## The tiers\n")
    w("| tier | definition |")
    w("|---|---|")
    w("| `initial` | Criteria transcribed from the source paper before any results were seen. "
      "An LLM or a human helping to DRAFT from the paper does not disqualify a run here; being "
      "revised against error reports does. |")
    w("| `manual` | The highest version whose criteria the author revised BY HAND, having "
      "inspected a few report examples. Light peeking. |")
    w("| `untuned` | The highest version whose criteria were NEVER iterated against this "
      "project's benchmark error reports. Permits LLM-authored criteria and LLM- or gold-tuned "
      "SEARCH; forbids criteria edited after seeing which studies or analyses the pipeline got "
      "wrong. Not a synonym for `manual`: it is set for five projects whose `manual` is empty, "
      "and for social it is HIGHER than `manual`. |")
    w("| `best` | The curated preferred run. Benchmark-informed tuning fully allowed. Selected on "
      "recall rather than F1 for canonical runs, because with a mixed pool a false positive may "
      "be a good paper the source meta-analysis never screened. |")
    w("| `latest` | Highest version number, mechanically. Kept as a sanity check. |")
    w("")
    w("`untuned` is the tier to cite for any claim that a result was not fitted to the "
      "benchmark. Where a family has no such run the registry says `untuned: null` explicitly; "
      "callers must skip those rather than auto-picking, which would silently substitute the "
      "tuned run.\n")

    w("## Registered runs\n")
    fams = ["canonical", "annotation_only", "allstudies"]
    w("Runs are marked `!` where the registered name has no outputs on disk, and `~` where a "
      "studyset exists but meta-analysis maps do not.\n")
    w("| project | family | " + " | ".join(f"`{t}`" for t in TIERS) + " |")
    w("|---" * (2 + len(TIERS)) + "|")
    for proj in sorted(reg):
        for fam in fams:
            f = (reg[proj] or {}).get(fam)
            if not isinstance(f, dict):
                continue
            cells = []
            for t in TIERS:
                v = f.get(t)
                if not v:
                    cells.append("—")
                    continue
                mark = {"no outputs": " `!`", "studyset only": " `~`"}.get(availability(proj, v), "")
                cells.append(f"`{v}`{mark}")
            w(f"| {proj} | {fam} | " + " | ".join(cells) + " |")
    w("")

    w("## What changes between tiers, per project\n")
    w("Canonical (search-driven) runs. Each row compares a tier against the one above it in the "
      "ladder, skipping tiers that resolve to the same run.\n")

    for proj in sorted(reg):
        fam = (reg[proj] or {}).get("canonical")
        if not isinstance(fam, dict):
            continue
        steps: list[tuple[str, str]] = []
        for t in LADDER:
            v = fam.get(t)
            if v and (not steps or steps[-1][1] != v):
                steps.append((t, v))
        w(f"### {proj}\n")
        if len(steps) == 1:
            t, v = steps[0]
            w(f"One run across the whole ladder: `{v}` "
              f"({', '.join(k for k in LADDER if fam.get(k) == v)}). Nothing to compare.\n")
            hdr = header(proj, v)
            if hdr:
                w(f"> {hdr}\n")
            continue
        w("| step | run | search | abstract screening | full-text screening | annotation |")
        w("|---|---|---|---|---|---|")
        for (t0, r0), (t1, r1) in zip(steps, steps[1:]):
            c0, c1 = cfg(proj, r0), cfg(proj, r1)
            if c0 is None or c1 is None:
                w(f"| {t0} -> {t1} | `{r1}` | config missing | | | |")
                continue
            w(f"| {t0} -> {t1} | `{r1}` | {search_delta(c0, c1)} "
              f"| {delta((c0.get('screening') or {}).get('abstract'), (c1.get('screening') or {}).get('abstract'))} "
              f"| {delta((c0.get('screening') or {}).get('fulltext'), (c1.get('screening') or {}).get('fulltext'))} "
              f"| {delta(c0.get('annotation'), c1.get('annotation'))} |")
        w("")
        cols = columns(cfg(proj, steps[-1][1]))
        if cols:
            w(f"Sub-annotation columns: {', '.join(f'`{c}`' for c in cols)}.")
            for (t0, r0), (t1, r1) in zip(steps, steps[1:]):
                a, b = columns(cfg(proj, r0)), columns(cfg(proj, r1))
                if a != b:
                    w(f"Columns change at {t0} -> {t1}: {a} -> {b}.")
            w("")
        for t, r in steps:
            hdr = header(proj, r)
            if hdr:
                w(f"- `{r}` ({t}) — {hdr}")
        w("")

    out = Path(args.output)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(L) + "\n")
    print(f"wrote {out.relative_to(REPO_ROOT)}  ({len(L)} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
