#!/usr/bin/env python3
"""Was the query the limiting factor for the text-to-map baselines?

WHY THIS EXISTS

`text_to_map_baselines.py` fixes one query per benchmark column in advance and refuses to revise
it against scores, which is the right discipline but leaves an obvious objection: maybe the arms
look weak because the queries were poor. This tests that.

HOW IT AVOIDS BECOMING THE THING IT IS TESTING

Per-column hand-tuning would be exactly the overfitting the pre-registration exists to prevent, so
the variants are generated by five UNIFORM strategies applied identically to all 32 columns:

    preregistered    the query in text_to_map_baselines.QUERIES
    column_name      the cleaned benchmark column name -- what a naive user would type
    project+column   the same, prefixed with the project's display name for context
    head_term        the last two words of the pre-registered query, i.e. its terse core
    plus_modality    the pre-registered query plus "fmri activation"

Each strategy is a defensible a priori choice, so its mean is a legitimate operating point. The
per-column MAXIMUM across strategies is also reported, clearly labelled: it is an oracle upper
bound that no user could achieve without the answers, and it exists to bound the objection rather
than to be quoted as a result.

A query a model cannot encode returns a constant map, whose correlation is undefined. Those score
0 -- no information -- rather than being dropped, and the count is reported.

NeuroQuery is queried live. NeuroVLM needs torch, so its variant maps are pre-generated in an
isolated venv into reports/neurovlm_variant_maps/ and scored from disk here.

Writes reports/query_sensitivity.csv.
"""

from __future__ import annotations

import argparse
import csv
import statistics as st
import sys
import warnings
from pathlib import Path

import numpy as np

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(Path(__file__).resolve().parent))
from text_to_map_baselines import gold_dir, UNCORRECTED_MAP  # noqa: E402
from make_brain_map_figure import pretty_column  # noqa: E402
from make_nature_methods_figures import DISPLAY  # noqa: E402
from map_mask import common_mask  # noqa: E402

STRATEGIES = ["preregistered", "column_name", "project+column", "head_term", "plus_modality"]


def variants(project: str, column: str, preregistered: str) -> dict[str, str]:
    col = pretty_column(project, column).lower()
    return {
        "preregistered": preregistered,
        "column_name": col,
        "project+column": f"{DISPLAY.get(project, project).lower()} {col}",
        "head_term": " ".join(preregistered.split()[-2:]),
        "plus_modality": f"{preregistered} fmri activation",
    }


def r2(candidate, gold_img, gold: np.ndarray) -> tuple[float, bool]:
    """(r-squared, was_degenerate). A constant map carries no information, so it scores 0."""
    from nilearn.image import resample_to_img

    pred = resample_to_img(candidate, gold_img, interpolation="continuous", force_resample=True)
    a = np.asarray(pred.dataobj)
    m = common_mask(a, gold)
    if a[m].std() == 0 or gold[m].std() == 0:
        return 0.0, True
    return float(np.corrcoef(a[m].ravel(), gold[m].ravel())[0, 1] ** 2), False


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--baselines", type=Path,
                    default=REPO_ROOT / "reports" / "text_to_map_baselines.csv")
    ap.add_argument("--neurovlm-variant-maps", type=Path,
                    default=REPO_ROOT / "reports" / "neurovlm_variant_maps")
    ap.add_argument("--output", type=Path,
                    default=REPO_ROOT / "reports" / "query_sensitivity.csv")
    args = ap.parse_args(argv)

    warnings.filterwarnings("ignore")
    import nibabel as nib
    from neuroquery import fetch_neuroquery_model, NeuroQueryModel

    rows = list(csv.DictReader(open(args.baselines)))
    nq_model = NeuroQueryModel.from_data_dir(fetch_neuroquery_model())

    out, degenerate = [], {("neuroquery", s): 0 for s in STRATEGIES}
    degenerate.update({("neurovlm", s): 0 for s in STRATEGIES})
    for r in rows:
        project, column = r["project"], r["manual_annotation"]
        gd = gold_dir(project, column)
        if gd is None or not (gd / UNCORRECTED_MAP).exists():
            continue
        gold_img = nib.load(str(gd / UNCORRECTED_MAP))
        gold = gold_img.get_fdata()
        for strategy, query in variants(project, column, r["query"]).items():
            rec = {"project": project, "manual_annotation": column,
                   "strategy": strategy, "query": query}
            v, deg = r2(nq_model(query)["brain_map"], gold_img, gold)
            rec["neuroquery_r2"] = round(v, 6)
            degenerate[("neuroquery", strategy)] += deg

            f = args.neurovlm_variant_maps / (
                f"{project}__{column}__{strategy.replace('+', '-')}.nii.gz")
            if f.exists():
                v, deg = r2(nib.load(str(f)), gold_img, gold)
                rec["neurovlm_r2"] = round(v, 6)
                degenerate[("neurovlm", strategy)] += deg
            else:
                rec["neurovlm_r2"] = ""
            out.append(rec)

    args.output.parent.mkdir(parents=True, exist_ok=True)
    with open(args.output, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(out[0]))
        w.writeheader()
        w.writerows(out)

    bb = st.mean([float(r["best_baseline_r2"]) for r in rows])
    pipe = st.mean([float(r["autonima_r2"]) for r in rows])
    for model, key in (("neuroquery", "neuroquery_r2"), ("neurovlm", "neurovlm_r2")):
        vals = {s: [float(x[key]) for x in out if x["strategy"] == s and x[key] != ""]
                for s in STRATEGIES}
        if not vals["preregistered"]:
            continue
        cols = sorted({(x["project"], x["manual_annotation"]) for x in out})
        oracle = []
        for c in cols:
            per = [float(x[key]) for x in out
                   if (x["project"], x["manual_annotation"]) == c and x[key] != ""]
            if per:
                oracle.append(max(per))
        print(f"\n{model}: mean r2 by query strategy (n={len(vals['preregistered'])})")
        for s in STRATEGIES:
            d = degenerate[(model, s)]
            print(f"  {s:16}{st.mean(vals[s]):.4f}" + (f"   ({d} constant maps)" if d else ""))
        print(f"  {'ORACLE max':16}{st.mean(oracle):.4f}   "
              f"= {st.mean(oracle) / bb:.1%} of the search baseline (upper bound only)")
        spread = []
        for c in cols:
            per = [float(x[key]) for x in out
                   if (x["project"], x["manual_annotation"]) == c and x[key] != ""]
            if len(per) > 1:
                spread.append(max(per) - min(per))
        print(f"  per-column spread: median {st.median(spread):.4f}, max {max(spread):.4f}")

    print(f"\n  reference: best search baseline {bb:.4f}, full pipeline {pipe:.4f}")
    print(f"  wrote {args.output.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
